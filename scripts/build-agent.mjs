// Bundles the shared agent core (lib/effect/agent) into api/_agent.mjs so the Vercel function
// imports plain JavaScript. Files starting with "_" in api/ are not deployed as functions.
// Usage: node scripts/build-agent.mjs [--check]   (--check fails when the committed bundle is stale)
import { buildSync } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(repo, 'api/_agent.mjs');

export function bundleAgent() {
  const r = buildSync({
    entryPoints: [resolve(repo, 'lib/effect/agent/index.ts')],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    write: false,
    legalComments: 'none',
    logLevel: 'warning',
  });
  return '// Generated by scripts/build-agent.mjs from lib/effect/agent — do not edit.\n' + r.outputFiles[0].text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const code = bundleAgent();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(out, 'utf8');
    } catch {
      /* missing */
    }
    if (current !== code) {
      console.error('api/_agent.mjs is stale: run `npm run build:agent`.');
      process.exit(1);
    }
    console.log('api/_agent.mjs is up to date.');
  } else {
    writeFileSync(out, code);
    console.log(`Agent bundle: ${out} (${Math.round(code.length / 1024)} KB)`);
  }
}
